    /** 敏感列可见角色：人事类数据集（薪资）对人事开放，其余为财务 / 管理层 */
    private static final Map<String, Set<String>> SENSITIVE_ROLES = Map.of(
            "employees", Set.of("ADMIN", "HR", "MANAGEMENT", "FINANCE"),
            "employee-changes", Set.of("ADMIN", "HR", "MANAGEMENT"),
            "employee-roster", Set.of("ADMIN", "HR"));                 // 花名册的明文敏感信息只给人事和管理员

    public static boolean canSeeSensitive(String role, String key) {
        Set<String> roles = SENSITIVE_ROLES.get(key);
        return roles != null ? roles.contains(role) : canSeeSensitive(role);
    }
